// Regenerates src/crypto-token-list.ts from the Uniswap default token list.
// Usage: node scripts/gen-crypto-token-list.mjs
import { writeFileSync } from "node:fs";

const CHAINS = [1, 8453, 42161, 10, 137];
const list = await (await fetch("https://tokens.uniswap.org")).json();
const rows = Object.fromEntries(CHAINS.map((id) => [id, []]));
for (const t of list.tokens) {
  if (!rows[t.chainId] || !/^0x[0-9a-fA-F]{40}$/.test(t.address) || !Number.isInteger(t.decimals))
    continue;
  rows[t.chainId].push([
    t.address.toLowerCase(),
    String(t.symbol).slice(0, 32),
    String(t.name).slice(0, 100),
    t.decimals,
  ]);
}
const body = CHAINS.map((id) => `  ${id}: ${JSON.stringify(rows[id])},`).join("\n");
writeFileSync(
  new URL("../src/crypto-token-list.ts", import.meta.url),
  `// Generated by scripts/gen-crypto-token-list.mjs from the Uniswap default token list (https://tokens.uniswap.org),\n// version ${["major", "minor", "patch"].map((k) => list.version[k]).join(".")}, ${list.timestamp}. Do not edit by hand.\n/** [address (lowercase), symbol, name, decimals] per chain id. */\nexport type TokenRow = readonly [address: string, symbol: string, name: string, decimals: number];\nexport const CRYPTO_TOKEN_LIST: Record<number, readonly TokenRow[]> = {\n${body}\n};\n`,
);
process.stdout.write(
  `${JSON.stringify(Object.fromEntries(CHAINS.map((id) => [id, rows[id].length])))}\n`,
);
